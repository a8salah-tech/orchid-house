--  علامة "راتب ثابت — بدون حضور" على الموظف
--  الموظف الذي عليه هذه العلامة (سواق / إدارة / أي موظف لا يسجّل بصمة ولا شيفتات):
--    • يأخذ راتبه كاملاً كل شهر تلقائياً (شهر عمل كامل).
--    • لا يُحتسب عليه خصم غياب ولا تأخير ولا خروج مبكر من جدول الحضور.
--    • لا يظهر له تحذير "لا يوجد أي شيفت مسجَّل".
--    • تبقى السلف والخصومات اليدوية كما هي (تُخصم من الراتب).
--  التشغيل: انسخ الملف كله في Supabase SQL Editor → Run. آمن لإعادة التشغيل.
-- ══════════════════════════════════════════════════════════════════════════════

alter table employees add column if not exists fixed_salary boolean not null default false;

comment on column employees.fixed_salary is
  'راتب ثابت بدون حضور — يُدفع الراتب كاملاً شهرياً بلا خصم غياب/تأخير ولا تحذير جدول شيفتات (سواقين/إدارة/موظفون بلا بصمة)';

notify pgrst, 'reload schema';
