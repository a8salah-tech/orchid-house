update violations
   set amount = 11.20,
       reason = reason || ' — صُحّح المبلغ من 4.8 إلى 11.20 (النسبة تخفيض: يتحمّل الموظف 70%)'
 where id = '10ef3688-07e4-4c68-a136-3a0eae913bd6'
   and amount = 4.8
   and reason not like '%صُحّح المبلغ%';

update violations
   set amount = 23.80,
       reason = reason || ' — صُحّح المبلغ من 10.2 إلى 23.80 (النسبة تخفيض: يتحمّل الموظف 70%)'
 where id = 'bb6788d9-a3e2-45ec-a6b2-85a80e0f8f36'
   and amount = 10.2
   and reason not like '%صُحّح المبلغ%';

