alter table payroll_records add column if not exists daily_hours numeric not null default 8;

comment on column payroll_records.daily_hours is
  'عدد ساعات الدوام اليومية لهذا الموظف هذا الشهر — محسوبة تلقائياً من شيفته الفعلي، تُستخدم كقاسم لحساب سعر الساعة بدل الرقم الثابت 8';

